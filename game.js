    if (x.needTag) {
      if (has(S, x.needTag)) y.from = originText(S, x.needTag) + ' 때문에 생긴 선택';
      else { y.locked = true; y.why = x.needWhy; }
    }
    if (x.blockTag && has(S, x.blockTag) && !(x.unless && has(S, x.unless))) {
      y.locked = true; y.why = originText(S, x.blockTag) + ' 때문에 ' + x.blockWhy;
    }
